var changelogRelease = regexp.MustCompile(`(?m)^## \[(\d+\.\d+\.\d+)\]\(`)

// changelogVersions lists every release-please section, newest first.
func changelogVersions(t *testing.T) []string {
	t.Helper()
	var out []string
	for _, m := range changelogRelease.FindAllStringSubmatch(repoFile(t, "CHANGELOG.md"), -1) {
		out = append(out, m[1])
	}
	if len(out) < 10 {
		t.Fatalf("found %d releases in CHANGELOG.md; the pattern is wrong", len(out))
	}
	return out
}

// Every release in CHANGELOG.md has its generated page, its data, and a place in
// the index, the feed and the sitemap. docs/releases/generate.py writes all of them.
func TestReleasePages_EveryChangelogReleaseHasAPage(t *testing.T) {
	index := repoFile(t, "docs", "releases", "index.html")
	feed := repoFile(t, "docs", "releases", "feed.xml")
	sitemap := repoFile(t, "docs", "sitemap.xml")
	for _, v := range changelogVersions(t) {
		page := "v" + v + ".html"
		src, err := os.ReadFile(filepath.Join("..", "..", "docs", "releases", page))
		if err != nil {
			t.Errorf("docs/releases/%s is missing; run python3 docs/releases/generate.py", page)
			continue
		}
		if !strings.Contains(string(src), "Generated by docs/releases/generate.py") {
			t.Errorf("docs/releases/%s was not written by the generator", page)
		}
		if _, err := os.Stat(filepath.Join("..", "..", "docs", "releases", "data", "v"+v+".json")); err != nil {
			t.Errorf("docs/releases/data/v%s.json is missing; run python3 docs/releases/generate.py fetch v%s", v, v)
		}
		url := "/releases/" + page
		for name, body := range map[string]string{"index.html": index, "feed.xml": feed, "sitemap.xml": sitemap} {
			if !strings.Contains(body, url) {
				t.Errorf("%s does not link %s", name, url)
			}
		}
	}
}

// The newest page is the version release-please is about to ship or just shipped,
// so the release PR cannot merge without its notes page.
func TestReleasePages_NewestMatchesManifest(t *testing.T) {
	var manifest map[string]string
	if err := json.Unmarshal([]byte(repoFile(t, ".release-please-manifest.json")), &manifest); err != nil {
		t.Fatal(err)
	}
	want := manifest["."]
	if got := changelogVersions(t)[0]; got != want {
		t.Fatalf("CHANGELOG.md's newest release is %s, the manifest says %s", got, want)
	}
	pages, err := filepath.Glob(filepath.Join("..", "..", "docs", "releases", "v*.html"))
	if err != nil {
		t.Fatal(err)
	}
	newest := ""
	for _, p := range pages {
		v := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(p), "v"), ".html")
		if newest == "" || versionLess(newest, v) {
			newest = v
		}
	}
	if newest != want {
		t.Errorf("the newest release page is v%s, the manifest says %s; run python3 docs/releases/generate.py", newest, want)
	}
}

// A page for a version CHANGELOG.md does not list would be notes for a release that never happened.
func TestReleasePages_NoPageWithoutARelease(t *testing.T) {
	known := map[string]bool{}
	for _, v := range changelogVersions(t) {
		known["v"+v+".html"] = true
	}
	pages, _ := filepath.Glob(filepath.Join("..", "..", "docs", "releases", "v*.html"))
	for _, p := range pages {
		if !known[filepath.Base(p)] {
			t.Errorf("docs/releases/%s has no section in CHANGELOG.md", filepath.Base(p))
		}
	}
}

func versionLess(a, b string) bool {
	pa, pb := strings.Split(a, "."), strings.Split(b, ".")
	for i := range pa {
		if len(pa[i]) != len(pb[i]) {
			return len(pa[i]) < len(pb[i])
		}
		if pa[i] != pb[i] {
			return pa[i] < pb[i]
		}
	}
	return false
}
