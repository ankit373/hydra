// Copies the Terrazzo CSS to the website and the desktop app, and writes the
// TUI's Lip Gloss v2 roles from every token that carries a terminal mapping.
import fs from 'node:fs';
import { MODES, read, walk, index, resolveHex } from './tokens.mjs';

const at = (p) => new URL(p, import.meta.url);

// Terrazzo copies an alias target's $description onto the alias, which
// mislabels them, so descriptions stay in the token source only.
const css = fs.readFileSync(at('../dist/tokens.css'), 'utf8')
  .replace(/^ +\/\*.*\*\/\n/gm, '')
  .replace(/\n{3,}/g, '\n\n')
  .replace('DO NOT EDIT!', 'DO NOT EDIT!\n *  Source: design/tokens, build: cd design && npm run build');
for (const out of ['../../docs/assets/tokens.css', '../../desktop/frontend/src/tokens.generated.css']) {
  fs.mkdirSync(at(out.replace(/[^/]+$/, '')), { recursive: true });
  fs.writeFileSync(at(out), css);
}

const primitives = read('primitives.tokens.json');
const base = read('base.tokens.json');
const themes = Object.fromEntries(MODES.map((m) => [m, read(`themes/${m}.tokens.json`)]));
const tokens = Object.fromEntries(MODES.map((m) => [m, index(primitives, base, themes[m])]));

const goName = (path) => 'tok' + path.replace(/^color\./, '').split(/[.-]/).map((s) => s[0].toUpperCase() + s.slice(1)).join('');
let vars = '';
const roles = [];
for (const [path, t] of walk(themes.light)) {
  const term = Object.fromEntries(MODES.map((m) => [m, tokens[m].get(path)?.$extensions?.['dev.hydra.terminal']]));
  if (!term.light) continue;
  if (!term.dark) throw new Error(`${path} has a terminal mapping in light but not in dark`);
  const name = goName(path);
  if (term.light.ansi16 === 'default') {
    vars += `\n// ${name} inherits the terminal's default foreground at every colour depth.\nvar ${name} color.Color = lipgloss.NoColor{}\n`;
    continue;
  }
  const cc = (m) => `tokDepths{TrueColor: "${resolveHex(tokens[m], path)}", ANSI256: "${term[m].ansi256}", ANSI: "${term[m].ansi16}"}`;
  vars += `\nvar ${name} = tokColor{\n\tLight: ${cc('light')},\n\tDark:  ${cc('dark')},\n}\n`;
  // One floor per role in Go, so take the stricter theme's.
  const min = Math.max(...MODES.map((m) => tokens[m].get(path).$extensions?.['dev.hydra.contrast']?.min ?? 0));
  roles.push(`\t{"${path}", ${name}, ${min}},\n`);
}

// Spacing reaches the TUI as whole cells, from each space token's terminal
// mapping; durations reach it as time.Duration.
const constBlock = (doc, rows) => {
  const w = Math.max(...rows.map(([n]) => n.length));
  return `${doc}\nconst (\n${rows.map(([n, v]) => `\t${n.padEnd(w)} = ${v}\n`).join('')})\n`;
};
const cells = [];
const durations = [];
for (const [path, t] of walk(base)) {
  const term = t.$extensions?.['dev.hydra.terminal'];
  if (term?.cells !== undefined) cells.push([goName(path), term.cells]);
  if (path.startsWith('motion.duration.')) durations.push([goName(path), `${t.$value.value} * time.Millisecond`]);
}
const layout =
  constBlock('// Padding in terminal cells. A cell is about 8px wide, so space.2 is one.', cells) + '\n' +
  constBlock('// Motion durations, the same values the desktop app and the website use.', durations);

const go = `// SPDX-License-Identifier: MIT

// Code generated by design/scripts/emit.mjs from design/tokens; DO NOT EDIT.

package tui

import (
	"image/color"
	"time"

	"charm.land/lipgloss/v2"
	"github.com/charmbracelet/colorprofile"
)

// tokDepths is one theme's value at each colour depth a terminal can show.
type tokDepths struct{ TrueColor, ANSI256, ANSI string }

// tokColor is a role on light and dark backgrounds, each with its own pick
// per depth rather than a downsampler's nearest match.
type tokColor struct{ Light, Dark tokDepths }

// at is the role's colour on a terminal of profile p; none below ANSI.
func (c tokColor) at(p colorprofile.Profile, dark bool) color.Color {
	pick := lipgloss.Complete(p)
	depth := func(d tokDepths) color.Color {
		return pick(lipgloss.Color(d.ANSI), lipgloss.Color(d.ANSI256), lipgloss.Color(d.TrueColor))
	}
	return lipgloss.LightDark(dark)(depth(c.Light), depth(c.Dark))
}
${vars}
${layout}
// tokRoles is every generated role with its WCAG 2 floor (0 = decorative).
var tokRoles = []struct {
	path string
	c    tokColor
	min  float64
}{
${roles.join('')}}
`;
fs.writeFileSync(at('../../internal/tui/tokens_gen.go'), go);

// The desktop app's native window paints surface.base for the OS theme before the
// webview's first frame, so neither theme flashes the other's background.
const rgba = (m) => {
  const [r, g, b] = [1, 3, 5].map((i) => '0x' + resolveHex(tokens[m], 'color.surface.base').slice(i, i + 2));
  return `options.RGBA{R: ${r}, G: ${g}, B: ${b}, A: 255}`;
};
fs.writeFileSync(at('../../desktop/window_gen.go'), `// SPDX-License-Identifier: MIT

// Code generated by design/scripts/emit.mjs from design/tokens; DO NOT EDIT.

package main

import "github.com/wailsapp/wails/v2/pkg/options"

// windowBackgroundLight and windowBackgroundDark are each theme's color.surface.base.
var (
	windowBackgroundLight = ${rgba('light')}
	windowBackgroundDark  = ${rgba('dark')}
)
`);
